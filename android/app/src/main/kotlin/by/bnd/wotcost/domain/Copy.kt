fun isLanguageId(value: String): Boolean = LanguageId.fromCode(value) != null

fun encyclopediaLanguage(id: LanguageId): String = ENCYCLOPEDIA[id] ?: "en"

fun matchingDeviceLanguage(tags: List<String>): LanguageId? {
    for (tag in tags) {
        val norm = tag.trim().lowercase().replace('_', '-')
        if (norm.isEmpty()) continue
        if (norm.startsWith("zh")) {
            if (norm.contains("hant") || norm.contains("-tw") || norm.contains("-hk") || norm.contains("-mo")) {
                return LanguageId.ZhTw
            }
            return LanguageId.ZhCn
        }
        if (norm.startsWith("pt")) return LanguageId.PtBr
        if (norm.startsWith("es")) return LanguageId.Es
        val primary = norm.substringBefore('-')
        val hit = LANGUAGES.find { it.id.code.lowercase() == primary }
        if (hit != null) return hit.id
    }
    return null
}

fun languageFromDevice(tags: List<String>): LanguageId =
    matchingDeviceLanguage(tags) ?: LanguageId.Ru

fun nativeName(id: LanguageId): String = LANGUAGES.first { it.id == id }.native

fun languageSubtitle(id: LanguageId, inLanguage: LanguageId): String? {
    val shownIn = Locale.forLanguageTag(inLanguage.code)
    val display = Locale.forLanguageTag(id.code).getDisplayName(shownIn).trim()
    if (display.isEmpty()) return null
    if (display.equals(nativeName(id), ignoreCase = true)) return null
    return display.replaceFirstChar { char ->
        if (char.isLowerCase()) char.titlecase(shownIn) else char.toString()
    }
}

fun suggestedLanguageIds(deviceMatch: LanguageId?, current: LanguagePreference): List<LanguageId> {
    val ids = linkedSetOf<LanguageId>()
    if (deviceMatch != null) ids.add(deviceMatch)
    ids.add(LanguageId.En)
    if (current is LanguagePreference.Fixed) ids.add(current.id)
    return ids.toList()
}

fun buildLanguageCatalog(
    text: Copy,
    preference: LanguagePreference,
    resolved: LanguageId,
    deviceTags: List<String>,
): LanguageCatalog {
    val suggestedIds = suggestedLanguageIds(matchingDeviceLanguage(deviceTags), preference)
    val suggestedSet = suggestedIds.toSet()
    val collator = Collator.getInstance(Locale.ROOT)
    val rest = LANGUAGES.map { it.id }
        .filter { it !in suggestedSet }
        .sortedWith(compareBy(collator) { nativeName(it) })
    return LanguageCatalog(
        device = LanguageOptionRow(
            preference = LanguagePreference.Device,
            title = text.languageDevice,
            subtitle = languageSubtitle(resolved, resolved) ?: nativeName(resolved),
            selected = preference is LanguagePreference.Device,
        ),
        suggestedTitle = text.suggested,
        suggested = suggestedIds.map { languageRow(it, preference, resolved) },
        allTitle = text.allLanguages,
        all = rest.map { languageRow(it, preference, resolved) },
    )
}

private fun languageRow(
    id: LanguageId,
    preference: LanguagePreference,
    resolved: LanguageId,
): LanguageOptionRow = LanguageOptionRow(
    preference = LanguagePreference.Fixed(id),
    title = nativeName(id),
    subtitle = languageSubtitle(id, resolved),
    selected = preference is LanguagePreference.Fixed && preference.id == id,
)

